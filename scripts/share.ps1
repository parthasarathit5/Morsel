# Foodiebay — share script
#
# The Django backend is not hosted on a server yet, so this script exposes the
# local API through a free Cloudflare quick tunnel, then rebuilds + redeploys
# the Firebase-hosted frontend so it points at the new tunnel URL.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File scripts\share.ps1            # web only
#   powershell -ExecutionPolicy Bypass -File scripts\share.ps1 -BuildApk  # web + APK
#
# Keep this window open while you use the app — closing it kills the tunnel.

param(
    [switch]$BuildApk
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$tools = Join-Path $root 'tools'
$firebaseProject = 'foodiebay-app-2026'
$backendPort = 8000

# --- 1) cloudflared ---------------------------------------------------------
$cloudflared = Join-Path $tools 'cloudflared.exe'
if (-not (Test-Path $cloudflared)) {
    New-Item -ItemType Directory -Force -Path $tools | Out-Null
    Write-Host "Downloading cloudflared..." -ForegroundColor Cyan
    Invoke-WebRequest -Uri 'https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-windows-amd64.exe' -OutFile $cloudflared
}

# --- 2) make sure the API is running ---------------------------------------
$listening = Get-NetTCPConnection -LocalPort $backendPort -State Listen -ErrorAction SilentlyContinue
if (-not $listening) {
    Write-Host "Starting Django on http://127.0.0.1:$backendPort ..." -ForegroundColor Cyan
    Start-Process -FilePath (Join-Path $root 'backend\.venv\Scripts\python.exe') `
        -ArgumentList 'manage.py', 'runserver', "127.0.0.1:$backendPort" `
        -WorkingDirectory (Join-Path $root 'backend')
    Start-Sleep -Seconds 4
}

# --- 3) start the tunnel and read its URL -----------------------------------
$log = Join-Path $env:TEMP 'foodiebay-tunnel.log'
if (Test-Path $log) { Remove-Item $log -Force }
$tunnel = Start-Process -FilePath $cloudflared `
    -ArgumentList 'tunnel', '--url', "http://127.0.0.1:$backendPort", '--no-autoupdate' `
    -NoNewWindow -PassThru -RedirectStandardError $log

$url = $null
for ($i = 0; $i -lt 60; $i++) {
    Start-Sleep -Seconds 1
    if (Test-Path $log) {
        $match = Select-String -Path $log -Pattern 'https://[a-z0-9-]+\.trycloudflare\.com' |
            Select-Object -First 1
        if ($match) { $url = $match.Matches[0].Value; break }
    }
}
if (-not $url) { throw "Could not read the tunnel URL. See $log" }
Write-Host "Tunnel: $url" -ForegroundColor Green

# --- 4) point the backend + frontend at the tunnel -------------------------
$envFile = Join-Path $root 'backend\.env'
$envText = Get-Content $envFile -Raw
$envText = $envText -replace '(?m)^DJANGO_ALLOWED_HOSTS=.*$', 'DJANGO_ALLOWED_HOSTS=.trycloudflare.com'
$envFileOut = $envText.TrimEnd() + "`n"
Set-Content -Path $envFile -Value $envFileOut -NoNewline

$prodEnv = Join-Path $root 'frontend\.env.production'
@(
    '# Production API base URL (Firebase Hosting + APK). Regenerated by scripts\share.ps1.',
    "VITE_API_BASE_URL=$url",
    ''
) | Set-Content -Path $prodEnv

# Restart Django so it picks up the env change.
$listening = Get-NetTCPConnection -LocalPort $backendPort -State Listen -ErrorAction SilentlyContinue
if ($listening) { Stop-Process -Id $listening.OwningProcess -Force }
Start-Process -FilePath (Join-Path $root 'backend\.venv\Scripts\python.exe') `
    -ArgumentList 'manage.py', 'runserver', "127.0.0.1:$backendPort" `
    -WorkingDirectory (Join-Path $root 'backend')

# --- 5) rebuild + redeploy the web app -------------------------------------
Push-Location (Join-Path $root 'frontend')
try {
    npm run build
    firebase deploy --only hosting --project $firebaseProject --non-interactive
} finally {
    Pop-Location
}
Write-Host "Web: https://$firebaseProject.web.app" -ForegroundColor Green

# --- 6) optionally rebuild the APK -----------------------------------------
if ($BuildApk) {
    $android = Join-Path $root 'frontend\android'
    $env:JAVA_HOME = 'C:\Program Files\Android\Android Studio\jbr'
    $env:ANDROID_HOME = "$env:LOCALAPPDATA\Android\Sdk"
    Push-Location (Join-Path $root 'frontend')
    try { npx cap sync android } finally { Pop-Location }
    Push-Location $android
    try { .\gradlew.bat assembleDebug --no-daemon } finally { Pop-Location }
    Copy-Item (Join-Path $android 'app\build\outputs\apk\debug\app-debug.apk') `
        (Join-Path $root 'Foodiebay.apk') -Force
    Write-Host "APK: $(Join-Path $root 'Foodiebay.apk')" -ForegroundColor Green
}

Write-Host ""
Write-Host "Tunnel + API are running. Press Ctrl+C to stop the tunnel." -ForegroundColor Yellow
Wait-Process -Id $tunnel.Id
